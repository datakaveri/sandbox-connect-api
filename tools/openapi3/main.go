// Command openapi3 builds openapi/openapi.yaml — the OpenAPI 3 operation
// manifest dx-gateway-go loads to enforce this service's per-operation
// authentication — from the Swagger 2.0 document swag generates.
//
// The swag annotations on each handler stay the single source of truth: every
// operation carries @ID and @x-dx-authz there, and this command only converts
// and adds the few routes swag cannot describe (the docs subtree and a
// deprecated alias). Run it through scripts/generate-openapi.sh; the
// conformance test in cmd/api fails when the result drifts from the router.
//
// Usage: go run ./tools/openapi3 [-in docs/swagger.json] [-out openapi/openapi.yaml]
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/getkin/kin-openapi/openapi2"
	"github.com/getkin/kin-openapi/openapi2conv"
	"github.com/getkin/kin-openapi/openapi3"
	"sigs.k8s.io/yaml"
)

const header = `# GENERATED by tools/openapi3 from docs/swagger.json (swag annotations).
# DO NOT EDIT — change the @ID / @x-dx-authz annotations on the handler and run
# scripts/generate-openapi.sh.
#
# This file is the service's OPERATION MANIFEST. dx-gateway-go loads it (as
# <operation_manifest_dir>/sandbox-connect-api.yaml) and enforces each
# operation's x-dx-authz; an operation not declared here is DENIED at the
# gateway. Paths are the service's own (after the gateway strips /sandbox).
`

func main() {
	in := flag.String("in", "docs/swagger.json", "swag-generated Swagger 2.0 document")
	out := flag.String("out", "openapi/openapi.yaml", "OpenAPI 3 manifest to write")
	flag.Parse()

	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "openapi3:", err)
		os.Exit(1)
	}
}

func run(in, out string) error {
	raw, err := os.ReadFile(filepath.Clean(in))
	if err != nil {
		return err
	}
	var doc2 openapi2.T
	if err := json.Unmarshal(raw, &doc2); err != nil {
		return fmt.Errorf("parse %s: %w", in, err)
	}
	doc, err := openapi2conv.ToV3(&doc2)
	if err != nil {
		return fmt.Errorf("convert: %w", err)
	}

	// The converter maps swag's apiKey definition literally; state it as what
	// it is, an HTTP bearer token.
	doc.Components.SecuritySchemes["BearerAuth"] = &openapi3.SecuritySchemeRef{
		Value: openapi3.NewJWTSecurityScheme().WithDescription(
			"Keycloak access token. Behind dx-gateway-go the gateway validates it and " +
				"forwards it (keep_authorization) together with the projected X-Subject-* headers.")}
	doc.Servers = openapi3.Servers{
		{URL: "/", Description: "Direct (API_AUTH_MODE=standalone)"},
		{URL: "/sandbox", Description: "Through dx-gateway-go (API_AUTH_MODE=gateway)"},
	}

	addExtras(doc)

	if err := doc.Validate(openapi3.NewLoader().Context); err != nil {
		return fmt.Errorf("generated document is invalid: %w", err)
	}
	js, err := json.Marshal(doc)
	if err != nil {
		return err
	}
	y, err := yaml.JSONToYAML(js)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(out, append([]byte(header), y...), 0o644) //nolint:gosec // committed source file
}

// addExtras declares the routes swag cannot annotate one-to-one.
func addExtras(doc *openapi3.T) {
	public := map[string]any{"authentication": "none"}

	// The ReDoc page and the spec files it serves (router.serveReDoc).
	docs := func(id, summary, mime string) *openapi3.PathItem {
		op := openapi3.NewOperation()
		op.OperationID = id
		op.Summary = summary
		op.Tags = []string{"docs"}
		op.Security = &openapi3.SecurityRequirements{}
		op.Extensions = map[string]any{"x-dx-authz": public}
		op.AddResponse(200, openapi3.NewResponse().WithDescription(summary).
			WithContent(openapi3.NewContentWithSchema(openapi3.NewStringSchema(), []string{mime})))
		return &openapi3.PathItem{Get: op}
	}
	doc.Paths.Set("/v1/apis", docs("getApiDocs", "API reference (ReDoc)", "text/html"))
	doc.Paths.Set("/v1/apis/swagger.json", docs("getSwaggerJSON", "Swagger 2.0 document (JSON)", "application/json"))
	doc.Paths.Set("/v1/apis/swagger.yaml", docs("getSwaggerYAML", "Swagger 2.0 document (YAML)", "application/yaml"))
	doc.Paths.Set("/v1/apis/openapi.yaml", docs("getOpenAPIManifest", "OpenAPI 3 operation manifest", "application/yaml"))

	// /v1/notebook/gpu-instance-types is the original name of instance-types
	// and is still routed to the same handler.
	if item := doc.Paths.Value("/v1/notebook/instance-types"); item != nil && item.Get != nil {
		alias := *item.Get
		alias.OperationID = "listGPUInstanceTypes"
		alias.Deprecated = true
		alias.Description = "Deprecated alias of GET /v1/notebook/instance-types."
		doc.Paths.Set("/v1/notebook/gpu-instance-types", &openapi3.PathItem{Get: &alias})
	}
}
